#!/usr/bin/env python3
"""Generate a compact C++ table for the TL constructors reachable from the
types the client parses. Functions are ignored; only data types matter."""
import re, sys, collections

SCHEMA = 'tools/reference/api.tl'
OUT_H = 'src/core/tl_schema.h'
OUT_CPP = 'src/core/tl_schema_gen.cpp'

PRIMS = {'int','long','int128','int256','double','string','bytes','Bool','true','Object','JSONValue'}

def parse():
    ctors = {}
    bytype = collections.defaultdict(list)
    for raw in open(SCHEMA, encoding='utf-8'):
        line = raw.strip()
        if not line or line.startswith('//') or line.startswith('---'):
            continue
        line = line.split('//', 1)[0].strip()
        m = re.match(r'^([A-Za-z_][\w\.]*)#([0-9a-fA-F]+)\s*(.*?)=\s*([\w\.<>]+);$', line)
        if not m:
            continue
        name, cid, rest, result = m.group(1), int(m.group(2), 16), m.group(3), m.group(4)
        fields = []
        for tok in rest.split():
            if ':' not in tok:
                continue
            fn, ft = tok.split(':', 1)
            fields.append((fn, ft))
        ctors[cid] = {'name': name, 'result': result, 'fields': fields}
        bytype[result].append(cid)
    return ctors, bytype

def base(t):
    flag = -1
    bit = 0
    m = re.match(r'^flags(2)?\.(\d+)\?(.+)$', t)
    if m:
        flag = 0 if m.group(1) is None else 1
        bit = int(m.group(2))
        t = m.group(3)
    if t.startswith('Vector<') and t.endswith('>'):
        return flag, bit, 'Vector', t[7:-1]
    if t.startswith('!') or t.startswith('%'):
        t = t[1:]
    if t in PRIMS:
        return flag, bit, t, None
    return flag, bit, 'Boxed', t

def closure(ctors, bytype, roots):
    seen = set()
    stack = []
    for r in roots:
        stack.extend(bytype.get(r, []))
    while stack:
        cid = stack.pop()
        if cid in seen: continue
        seen.add(cid)
        for fn, ft in ctors[cid]['fields']:
            flag, bit, kind, ref = base(ft)
            if kind == 'Boxed':
                stack.extend(bytype.get(ref, []))
            elif kind == 'Vector' and ref and ref not in PRIMS:
                stack.extend(bytype.get(ref, []))
    return seen

def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

def main():
    ctors, bytype = parse()
    roots = ['User','Chat','Channel','Dialog','Message','Peer','auth.Authorization','auth.LoginToken','Config','messages.Dialogs','messages.Messages','updates.State','account.Password']
    keep = closure(ctors, bytype, roots)
    keep_sorted = sorted(keep)
    print('constructors:', len(keep_sorted), file=sys.stderr)

    hdr = '''// Generated by tools/gen_tl.py. Do not edit.
#pragma once
#include <cstdint>
namespace tgnx::tl {
enum class FieldType : uint8_t { Int, Long, Int128, Int256, Double, String, Bytes, Bool, True, Object, Vector, Boxed };
struct FieldDef { const char* name; const char* ref; FieldType type; int8_t flag; uint8_t bit; };
struct CtorDef { uint32_t id; const char* name; const FieldDef* fields; uint16_t count; uint8_t hasFlags; uint8_t hasFlags2; };
const CtorDef* findCtor(uint32_t id);
extern const CtorDef kCtors[];
extern const unsigned kCtorCount;
}  // namespace tgnx::tl
'''
    open(OUT_H, 'w').write(hdr)

    lines = ['// Generated by tools/gen_tl.py. Do not edit.', '#include "core/tl_schema.h"', '#include <cstring>', '', 'namespace tgnx::tl {', '']
    for cid in keep_sorted:
        c = ctors[cid]
        fields = []
        for fn, ft in c['fields']:
            flag, bit, kind, ref = base(ft)
            if fn == 'flags' and ft == '#': continue
            if fn == 'flags2' and ft == '#': continue
            if kind in ('int',): typ = 'FieldType::Int'
            elif kind == 'long': typ = 'FieldType::Long'
            elif kind == 'int128': typ = 'FieldType::Int128'
            elif kind == 'int256': typ = 'FieldType::Int256'
            elif kind == 'double': typ = 'FieldType::Double'
            elif kind == 'string': typ = 'FieldType::String'
            elif kind == 'bytes': typ = 'FieldType::Bytes'
            elif kind == 'Bool': typ = 'FieldType::Bool'
            elif kind == 'true': typ = 'FieldType::True'
            elif kind == 'Object': typ = 'FieldType::Object'
            elif kind == 'JSONValue': typ = 'FieldType::Object'
            elif kind == 'Vector': typ = 'FieldType::Vector'
            elif kind == 'Boxed': typ = 'FieldType::Boxed'
            else: continue
            fields.append((fn, typ, ref or '', flag, bit))
        arr = f'kFields_{cid:08x}'
        lines.append(f'static const FieldDef {arr}[] = {{')
        for fn, typ, ref, flag, bit in fields:
            lines.append(f'    {{{cstr(fn)}, {cstr(ref) if ref else "nullptr"}, {typ}, {flag}, {bit}}},')
        if not fields:
            lines.append('    {nullptr, nullptr, FieldType::Int, -1, 0},')
        lines.append('};')
    lines.append('')
    lines.append('const CtorDef kCtors[] = {')
    for cid in keep_sorted:
        c = ctors[cid]
        has_flags = int(any(fn == 'flags' and ft == '#' for fn, ft in c['fields']))
        has_flags2 = int(any(fn == 'flags2' and ft == '#' for fn, ft in c['fields']))
        lines.append(f'    {{0x{cid:08x}u, {cstr(c["name"])}, kFields_{cid:08x}, (uint16_t)(sizeof(kFields_{cid:08x}) / sizeof(FieldDef)), {has_flags}, {has_flags2}}},')
    lines.append('};')
    lines.append('const unsigned kCtorCount = sizeof(kCtors) / sizeof(kCtors[0]);')
    lines.append('''
const CtorDef* findCtor(uint32_t id) {
    unsigned lo = 0, hi = kCtorCount;
    while (lo < hi) {
        unsigned mid = (lo + hi) / 2;
        if (kCtors[mid].id == id) return &kCtors[mid];
        if (kCtors[mid].id < id) lo = mid + 1;
        else hi = mid;
    }
    return nullptr;
}
}  // namespace tgnx::tl
''')
    open(OUT_CPP, 'w').write('\n'.join(lines))
    import os
    print('wrote', os.path.getsize(OUT_CPP), 'bytes', file=sys.stderr)

if __name__ == '__main__':
    main()
